CREATE TABLE IF NOT EXISTS attendance_corrections (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    client_id INT NOT NULL,
    employee_id INT NOT NULL,
    work_date DATE NOT NULL,
    kind ENUM('check_in','check_out','missing_checkout','missing_attendance') NOT NULL,
    request_key CHAR(32) NOT NULL,
    reason VARCHAR(1000) NOT NULL,
    status ENUM('pending','approved','rejected','canceled') NOT NULL DEFAULT 'pending',
    source_attendance_id INT NULL,
    source_check_in_at DATETIME NULL,
    source_check_out_at DATETIME NULL,
    base_correction_id BIGINT NULL,
    base_check_in_at DATETIME NULL,
    base_check_out_at DATETIME NULL,
    proposed_check_in_at DATETIME NOT NULL,
    proposed_check_out_at DATETIME NULL,
    office_id INT NOT NULL,
    office_name VARCHAR(120) NOT NULL,
    scheduled_start TIME NOT NULL,
    scheduled_end TIME NOT NULL,
    late_minutes INT NOT NULL DEFAULT 0,
    submitted_by INT NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reviewed_by INT NULL,
    reviewed_at DATETIME NULL,
    admin_note VARCHAR(500) NOT NULL DEFAULT '',
    pending_work_date DATE GENERATED ALWAYS AS (CASE WHEN status='pending' THEN work_date ELSE NULL END) STORED,
    UNIQUE KEY uq_correction_request (client_id, employee_id, request_key),
    UNIQUE KEY uq_correction_pending (client_id, employee_id, pending_work_date),
    UNIQUE KEY uq_correction_tenant (id, client_id),
    INDEX idx_correction_effective (client_id, employee_id, work_date, status, id),
    INDEX idx_correction_queue (client_id, status, id),
    CONSTRAINT fk_correction_employee FOREIGN KEY (employee_id, client_id) REFERENCES employees(id, client_id),
    CONSTRAINT fk_correction_submitter FOREIGN KEY (submitted_by, client_id) REFERENCES users(id, client_id),
    CONSTRAINT fk_correction_reviewer FOREIGN KEY (reviewed_by, client_id) REFERENCES users(id, client_id),
    CONSTRAINT fk_correction_office FOREIGN KEY (office_id, client_id) REFERENCES office_locations(id, client_id),
    CONSTRAINT chk_correction_order CHECK (proposed_check_out_at IS NULL OR proposed_check_out_at > proposed_check_in_at),
    CONSTRAINT chk_correction_day CHECK (DATE(proposed_check_in_at)=work_date AND (proposed_check_out_at IS NULL OR DATE(proposed_check_out_at)=work_date))
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS attendance_correction_audit (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    client_id INT NOT NULL,
    correction_id BIGINT NOT NULL,
    actor_id INT NOT NULL,
    action ENUM('submitted','approved','rejected','canceled') NOT NULL,
    note VARCHAR(1000) NOT NULL DEFAULT '',
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    INDEX idx_correction_audit (client_id, correction_id, id),
    CONSTRAINT fk_correction_audit_request FOREIGN KEY (correction_id, client_id) REFERENCES attendance_corrections(id, client_id),
    CONSTRAINT fk_correction_audit_actor FOREIGN KEY (actor_id, client_id) REFERENCES users(id, client_id)
) ENGINE=InnoDB;
